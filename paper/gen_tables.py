"""Generate the paper's result tables straight from the raw per-run data, so
no number in the paper is typed by hand.

Usage (from paper/): python3 gen_tables.py ../research/replan/data/r1.jsonl \
    ../research/replan/data/r2.jsonl > tables.tex
"""
import json
import sys

ROWS = [(g, k) for g in ("turn", "step") for k in ("tool_call_id", "args_hash", "position")]
TEMPS = (0.0, 0.7, 1.0)
KEYNAME = {"tool_call_id": r"\texttt{tool\_call\_id}", "args_hash": r"\texttt{args\_hash}",
           "position": r"\texttt{position}"}


def load(path, round_name):
    rows = []
    for line in open(path):
        if line.strip():
            r = json.loads(line)
            r.setdefault("task", "credit")
            r["round"] = round_name
            rows.append(r)
    return rows


def cell(rows, field):
    n = [r for r in rows if r["kill_triggered"]]
    if not n:
        return "---"
    k = sum(r[field] for r in n)
    return f"{round(100 * k / len(n))} {{\\scriptsize({len(n)})}}"


def table(rows, model, field, tasks, caption, label):
    out = [r"\begin{table}[t]", r"\centering", r"\small",
           r"\begin{tabular}{ll" + "ccc" * len(tasks) + "}", r"\toprule",
           " & & " + " & ".join(rf"\multicolumn{{3}}{{c}}{{{t}}}" for t in tasks) + r" \\",
           " & & " + " & ".join(" & ".join(f"$T{{=}}{t:g}$" for t in TEMPS) for _ in tasks) + r" \\",
           r"\midrule"]
    for g, k in ROWS:
        vals = []
        for task in tasks:
            for t in TEMPS:
                sel = [r for r in rows if r["model"] == model and r["granularity"] == g
                       and r["keys"] == k and r["temperature"] == t and r["task"] == task]
                vals.append(cell(sel, field))
        out.append(f"{g} & {KEYNAME[k]} & " + " & ".join(vals) + r" \\")
        if (g, k) == ("turn", "position"):
            out.append(r"\midrule")
    out += [r"\bottomrule", r"\end{tabular}", rf"\caption{{{caption}}}", rf"\label{{{label}}}",
            r"\end{table}", ""]
    return "\n".join(out)


def main(r1_path, r2_path):
    r1 = load(r1_path, "R1")
    r2 = load(r2_path, "R2")
    note = (r"Cells: \% of kill-triggered runs (n in parentheses); --- = no run reached the fault. "
            r"Generated by \texttt{paper/gen\_tables.py} from the raw data.")
    print(table(r1, "qwen2.5:3b", "duplicate", ["credit"],
                "Round 1 (Apple M1, serial), qwen2.5:3b: duplicate rate. " + note, "tab:r1"))
    print(table(r2, "qwen2.5:3b", "duplicate", ["credit", "memo", "two"],
                "Round 2 (A100, 16 concurrent), qwen2.5:3b: duplicate rate. " + note, "tab:r2dup"))
    print(table(r2, "llama3.2:3b", "duplicate", ["credit", "memo", "two"],
                "Round 2, llama3.2:3b: duplicate rate. " + note, "tab:r2dupllama"))
    for model in ("qwen2.5:3b", "llama3.2:3b"):
        print(table(r2, model, "lost_effect", ["two"],
                    f"Round 2, task \\emph{{two}}, {model}: lost-effect rate. " + note,
                    "tab:r2lost" + model.split(".")[0]))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
